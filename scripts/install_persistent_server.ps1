# Install CRM Compare Tool as a Windows Scheduled Task (no password stored).
# Requires Administrator. Creates .env with CRM_API_TOKEN if missing.
#Requires -RunAsAdministrator
param(
    [string]$ProjectDir = "",
    [int]$HttpPort = 5000,
    [int]$HttpsPort = 5443,
    [ValidateSet("Auto", "System", "Interactive")]
    [string]$RunAs = "Auto"
)

$ErrorActionPreference = "Stop"
$TaskName = "CRMCompareToolServer"

if (-not $ProjectDir) {
    $ProjectDir = Split-Path $PSScriptRoot -Parent
}
$ProjectDir = (Resolve-Path $ProjectDir).Path

$PythonExe = Join-Path $ProjectDir ".venv\Scripts\python.exe"
$RunnerScript = Join-Path $ProjectDir "scripts\server_service_runner.py"
$EnvFile = Join-Path $ProjectDir ".env"

if (-not (Test-Path $PythonExe)) {
    throw "Python venv not found: $PythonExe - create .venv first."
}
if (-not (Test-Path $RunnerScript)) {
    throw "Service runner not found: $RunnerScript"
}

function New-RandomToken {
    $bytes = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return [Convert]::ToBase64String($bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function Ensure-ServerEnvFile {
    param([string]$Path)
    $token = New-RandomToken
    $jarSecret = New-RandomToken
    $lines = @(
        "# Auto-generated by INSTALL_PERSISTENT_SERVER.bat - do not commit",
        "CRM_API_TOKEN=$token",
        "CRM_JAR_DOWNLOAD_SECRET=$jarSecret",
        "CRM_REQUIRE_SECURE=1",
        "CRM_OPEN_FIREWALL=1",
        "HOST=0.0.0.0",
        "PORT=$HttpPort",
        "HTTPS_PORT=$HttpsPort",
        "CRM_USE_HTTPS=0",
        "CRM_ENABLE_ADMIN=0",
        "CRM_ENABLE_DEV_ROUTES=0",
        "CRM_SSH_HTTPS_ONLY=0",
        "CRM_SSH_STRICT_HOSTKEY=0"
    )
    if (Test-Path $Path) {
        $existing = Get-Content $Path -Raw
        if ($existing -match '(?m)^CRM_API_TOKEN=') {
            Write-Host "[OK] Using existing .env (CRM_API_TOKEN already set)." -ForegroundColor Green
            return $null
        }
        Add-Content -Path $Path -Value "`nCRM_API_TOKEN=$token"
        Write-Host "[OK] Added CRM_API_TOKEN to existing .env file." -ForegroundColor Green
        return $token
    }
    Set-Content -Path $Path -Value ($lines -join "`n") -Encoding UTF8
    Write-Host "[OK] Created .env with security settings and access token." -ForegroundColor Green
    return $token
}

$accessToken = Ensure-ServerEnvFile -Path $EnvFile
if (-not $accessToken -and (Test-Path $EnvFile)) {
    $match = Select-String -Path $EnvFile -Pattern '^CRM_API_TOKEN=(.+)$' | Select-Object -First 1
    if ($match) { $accessToken = $match.Matches[0].Groups[1].Value.Trim() }
}

$onOneDrive = $ProjectDir -match "OneDrive"

if ($RunAs -eq "Auto") {
    if ($onOneDrive) { $RunAs = "Interactive" } else { $RunAs = "System" }
}

if ($RunAs -eq "System" -and $onOneDrive) {
    throw "Cannot use SYSTEM mode on a OneDrive path. Move project to local disk (e.g. C:\tools\python_project)."
}

Write-Host ""
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "  Install CRM Compare server (secured scheduled task)" -ForegroundColor Cyan
Write-Host "  No Windows password stored" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "  Project:  $ProjectDir"
Write-Host "  HTTP:     $HttpPort (secured with CRM_API_TOKEN)"
Write-Host "  Run as:   $RunAs"
Write-Host ""

if ($RunAs -eq "Interactive") {
    Write-Host "[INFO] Interactive: starts at login, stops at logoff." -ForegroundColor Yellow
} else {
    Write-Host "[INFO] SYSTEM: starts at boot (Windows Server recommended)." -ForegroundColor Yellow
}
Write-Host "[INFO] Remote access requires CRM_API_TOKEN from .env (never share by email)." -ForegroundColor Yellow
Write-Host ""

Write-Host "Stopping any existing listeners on ports $HttpPort / $HttpsPort ..."
foreach ($p in @($HttpPort, $HttpsPort)) {
    try {
        Get-NetTCPConnection -LocalPort $p -State Listen -ErrorAction SilentlyContinue |
            ForEach-Object { Stop-Process -Id $_.OwningProcess -Force -ErrorAction SilentlyContinue }
    } catch {
        Write-Host "  (skipped port cleanup for port $p)"
    }
}

$existing = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
if ($existing) {
    Write-Host "Removing previous scheduled task '$TaskName' ..."
    Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}

$Action = New-ScheduledTaskAction `
    -Execute $PythonExe `
    -Argument "`"$RunnerScript`" --host 0.0.0.0 --port $HttpPort --no-https" `
    -WorkingDirectory $ProjectDir

$Settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -ExecutionTimeLimit ([TimeSpan]::Zero) `
    -RestartCount 999 `
    -RestartInterval (New-TimeSpan -Minutes 1) `
    -MultipleInstances IgnoreNew `
    -StartWhenAvailable

if ($RunAs -eq "System") {
    $Trigger = New-ScheduledTaskTrigger -AtStartup
    $Principal = New-ScheduledTaskPrincipal -UserId "SYSTEM" -LogonType ServiceAccount -RunLevel Highest
    Register-ScheduledTask -TaskName $TaskName -Action $Action -Trigger $Trigger -Settings $Settings -Principal $Principal -Force | Out-Null
} else {
    $userName = (whoami.exe 2>$null).Trim()
    if (-not $userName) { $userName = "$env:USERDOMAIN\$env:USERNAME" }
    Write-Host "Registering task for: $userName (Interactive)"
    $Trigger = New-ScheduledTaskTrigger -AtLogon -User $userName
    $Principal = New-ScheduledTaskPrincipal -UserId $userName -LogonType Interactive -RunLevel Limited
    Register-ScheduledTask -TaskName $TaskName -Action $Action -Trigger $Trigger -Settings $Settings -Principal $Principal -Force | Out-Null
}

Write-Host "[OK] Scheduled task '$TaskName' registered." -ForegroundColor Green

Write-Host "Adding firewall rules (domain/private profiles only) ..."
foreach ($p in @($HttpPort, $HttpsPort)) {
    $ruleName = "CRM Compare Tool TCP $p"
    $check = netsh advfirewall firewall show rule name="$ruleName" 2>$null
    if ($LASTEXITCODE -ne 0 -or ($check -match "No rules match")) {
        netsh advfirewall firewall add rule name="$ruleName" dir=in action=allow protocol=TCP localport=$p profile=domain,private | Out-Null
        Write-Host "  Added firewall rule for TCP $p"
    } else {
        Write-Host "  Firewall rule for TCP $p already exists"
    }
}

Write-Host "Starting server task ..."
Start-ScheduledTask -TaskName $TaskName
Start-Sleep -Seconds 4

$listening = $null
try {
    $listening = Get-NetTCPConnection -LocalPort $HttpPort -State Listen -ErrorAction SilentlyContinue
} catch { $listening = $null }

if ($listening) {
    Write-Host "[SUCCESS] Server is listening on port $HttpPort" -ForegroundColor Green
} else {
    Write-Host "[WARN] Port $HttpPort not listening yet - check logs\builtin_server_service.log" -ForegroundColor Yellow
}

$ips = @()
try {
    $ips = @(Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
        Where-Object { $_.IPAddress -notmatch '^127\.' -and $_.IPAddress -notmatch '^169\.' } |
        ForEach-Object { $_.IPAddress } | Select-Object -Unique)
} catch { $ips = @() }

Write-Host ""
Write-Host "Secured access URLs (share token separately via approved channel):" -ForegroundColor Cyan
Write-Host "  Admin: read token from $EnvFile"
if ($accessToken) {
    Write-Host "  Example: http://127.0.0.1:${HttpPort}/crm?access_token=$accessToken"
}
foreach ($ip in $ips) {
    Write-Host "  Network: http://${ip}:${HttpPort}/crm?access_token=<token-from-env>"
}
Write-Host ""
Write-Host "Log file: $ProjectDir\logs\builtin_server_service.log"
Write-Host ""
Write-Host "To remove: UNINSTALL_PERSISTENT_SERVER.bat (as Administrator)"
Write-Host "To stop:   STOP_SERVER.bat"
Write-Host ""
